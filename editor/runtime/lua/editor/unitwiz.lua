local function AddBox(m, x0, y0, z0, x1, y1, z1, bone)
    -- 6 faces, 4 vertices each, counter clockwise seen from outside; uv in the faces' own 0..1
    local faces = {
        { { 0, 0, 1 }, { x0, y0, z1 }, { x1, y0, z1 }, { x1, y1, z1 }, { x0, y1, z1 }, { 1, 0, 0 } },       -- +z
        { { 0, 0, -1 }, { x1, y0, z0 }, { x0, y0, z0 }, { x0, y1, z0 }, { x1, y1, z0 }, { -1, 0, 0 } },     -- -z
        { { 1, 0, 0 }, { x1, y0, z1 }, { x1, y0, z0 }, { x1, y1, z0 }, { x1, y1, z1 }, { 0, 0, -1 } },      -- +x
        { { -1, 0, 0 }, { x0, y0, z0 }, { x0, y0, z1 }, { x0, y1, z1 }, { x0, y1, z0 }, { 0, 0, 1 } },      -- -x
        { { 0, 1, 0 }, { x0, y1, z1 }, { x1, y1, z1 }, { x1, y1, z0 }, { x0, y1, z0 }, { 1, 0, 0 } },       -- +y
        { { 0, -1, 0 }, { x0, y0, z0 }, { x1, y0, z0 }, { x1, y0, z1 }, { x0, y0, z1 }, { 1, 0, 0 } },      -- -y
    }
    local uv = { { 0, 1 }, { 1, 1 }, { 1, 0 }, { 0, 0 } }
    for _, f in faces do
        local base = m.n
        local n, tan = f[1], f[6]
        local bin = { n[2] * tan[3] - n[3] * tan[2], n[3] * tan[1] - n[1] * tan[3], n[1] * tan[2] - n[2] * tan[1] }
        for i = 1, 4 do
            local p = f[i + 1]
            local a, b = m.n * 3, m.n * 2
            m.pos[a + 1], m.pos[a + 2], m.pos[a + 3] = p[1], p[2], p[3]
            m.nrm[a + 1], m.nrm[a + 2], m.nrm[a + 3] = n[1], n[2], n[3]
            m.tan[a + 1], m.tan[a + 2], m.tan[a + 3] = tan[1], tan[2], tan[3]
            m.bin[a + 1], m.bin[a + 2], m.bin[a + 3] = bin[1], bin[2], bin[3]
            m.uv1[b + 1], m.uv1[b + 2] = uv[i][1], uv[i][2]
            m.uv2[b + 1], m.uv2[b + 2] = uv[i][1], uv[i][2]
            m.bone[m.n + 1] = bone
            m.n = m.n + 1
        end
        local ix = table.getn(m.idx)
        for k, v in { 1, 2, 3, 1, 3, 4 } do m.idx[ix + k] = base + v end
    end
end

local function BoneIndex(bones, name)
    if not name then return nil end
    local lower = string.lower(name)
    for i, b in bones do
        if string.lower(b.name) == lower then return i - 1 end
    end
    return nil
end

--- A box-and-turret placeholder in the template's skeleton, in the donor's proportions scaled to the spec's length.
local function Placeholder(spec, bones)
    local d = Donor(spec)
    local f = SkeletonScale(spec)
    local b = d.bounds
    local x0, y0, z0, x1, y1, z1 = b[1] * f, b[2] * f, b[3] * f, b[4] * f, b[5] * f, b[6] * f
    local w, h, l = x1 - x0, y1 - y0, z1 - z0
    local m = Scm.New()
    m.bone = {}
    local pos = Scm.BonePositions(bones)
    -- the body: the lower 60 % of the bounds, tapered nothing; the root bone drives it
    AddBox(m, x0 + w * 0.08, y0, z0 + l * 0.05, x1 - w * 0.08, y0 + h * 0.55, z1 - l * 0.05, 0)
    local wb = WeaponBones(spec)
    if wb and wb.yaw and table.getn(spec.weapons or {}) > 0 then
        local yi = BoneIndex(bones, wb.yaw)
        local pi_ = BoneIndex(bones, wb.pitch) or yi
        if yi then
            local p = pos[yi + 1]
            local tw = math.min(w, l) * 0.28
            AddBox(m, p[1] - tw, math.max(y0 + h * 0.45, p[2] - tw * 0.5), p[3] - tw, p[1] + tw, math.max(y0 + h * 0.45, p[2] - tw * 0.5) + tw * 1.1, p[3] + tw, yi)
            local q = pos[(pi_ or yi) + 1]
            local bw = tw * 0.25
            AddBox(m, q[1] - bw, q[2] - bw, q[3], q[1] + bw, q[2] + bw, q[3] + l * 0.38, pi_ or yi)
        end
    else
        -- a nose so the front (+z) can be told from the back
        AddBox(m, -w * 0.12, y0 + h * 0.55, z1 - l * 0.3, w * 0.12, y0 + h * 0.8, z1 - l * 0.05, 0)
    end
    return m
end

local function Rotate(obj, yaw)
    if yaw == 0 then return end
    local c, s = math.cos(yaw), math.sin(yaw)
    local function Do(a, n)
        for i = 0, n - 1 do
            local x, z = a[i * 3 + 1], a[i * 3 + 3]
            a[i * 3 + 1], a[i * 3 + 3] = x * c + z * s, -x * s + z * c
        end
    end
    Do(obj.v, obj.nv)
    Do(obj.vn, obj.nvn)
end

--- Builds the unit mesh: from the OBJ text when there is one, else a placeholder. -> mesh (with bones and bone), info { vertices, triangles, bounds (mesh units), groups, bones, warnings, placeholder }
function BuildMesh(spec, objText)
    local d = Donor(spec)
    local us = d.uniformScale or 0.1
    local info = { warnings = {}, groups = {}, placeholder = false }
    local mo = spec.mesh
    local bones
    local mesh
    if objText and objText ~= '' then
        local obj = MeshImport.ParseObj(objText, 'object')
        if obj.nv == 0 or table.getn(obj.groups) == 0 then return nil, 'the OBJ file has no faces' end
        for _, wmsg in obj.warnings do table.insert(info.warnings, wmsg) end
        Rotate(obj, mo.yaw or 0)
        -- scale: the longest horizontal side of the model becomes the spec's length
        local probe = MeshImport.Build(obj, { axis = mo.axis, mirrorX = mo.mirrorX, flipWinding = mo.flipWinding, flipV = mo.flipV, groupBy = 'object', scale = 1, limit = 1000000 })
        local x0, y0, z0, x1, y1, z1
        for _, g in probe.groups do
            local a, b, c, dd, e, ff = Scm.Bounds(g.mesh)
            if a then
                if not x0 then x0, y0, z0, x1, y1, z1 = a, b, c, dd, e, ff
                else
                    x0, y0, z0 = math.min(x0, a), math.min(y0, b), math.min(z0, c)
                    x1, y1, z1 = math.max(x1, dd), math.max(y1, e), math.max(z1, ff)
                end
            end
        end
        if not x0 then return nil, 'the OBJ has no usable triangle' end
        local side = math.max(x1 - x0, z1 - z0)
        if side < 1e-9 then return nil, 'the OBJ has no horizontal size' end
        local scale = (mo.length / us) / side
        local result = MeshImport.Build(obj, { axis = mo.axis, mirrorX = mo.mirrorX, flipWinding = mo.flipWinding, flipV = mo.flipV, groupBy = 'object', scale = scale,
                                               offsetX = -(x0 + x1) / 2 * scale, offsetY = -y0 * scale, offsetZ = -(z0 + z1) / 2 * scale, limit = 1000000 })
        for _, wmsg in result.warnings do table.insert(info.warnings, wmsg) end
        -- bones
        local groupNames = {}
        for _, g in result.groups do table.insert(groupNames, g.name) end
        if mo.skeleton == 'groups' then
            bones = { { name = string.upper(spec.id), parent = -1, pos = { 0, 0, 0 }, rot = { 1, 0, 0, 0 } } }
            local order = {}
            for _, g in result.groups do
                local a, b, c, dd, e, ff = Scm.Bounds(g.mesh)
                table.insert(bones, { name = g.name, parent = 0, pos = { (a + dd) / 2, (b + e) / 2, (c + ff) / 2 }, rot = { 1, 0, 0, 0 } })
            end
            info.groups = groupNames
        else
            bones = TemplateBones(spec)
        end
        mesh = Scm.New()
        mesh.bone = {}
        for _, g in result.groups do
            local gm = g.mesh
            local bone = BoneIndex(bones, g.name) or 0
            if mo.skeleton == 'template' and not BoneIndex(bones, g.name) and g.name ~= 'default' and g.name ~= 'mesh' then
                table.insert(info.warnings, "group '" .. g.name .. "' is not a bone of the template skeleton: bound to the root bone")
            end
            local base = mesh.n
            for i = 1, gm.n * 3 do mesh.pos[base * 3 + i] = gm.pos[i] mesh.nrm[base * 3 + i] = gm.nrm[i] mesh.tan[base * 3 + i] = gm.tan[i] mesh.bin[base * 3 + i] = gm.bin[i] end
            for i = 1, gm.n * 2 do mesh.uv1[base * 2 + i] = gm.uv1[i] mesh.uv2[base * 2 + i] = gm.uv2[i] end
            for i = 1, gm.n do mesh.bone[base + i] = bone end
            local ix = table.getn(mesh.idx)
            for i, v in gm.idx do mesh.idx[ix + i] = v + base end
            mesh.n = base + gm.n
        end
    else
        bones = TemplateBones(spec)
        mesh = Placeholder(spec, bones)
        info.placeholder = true
        table.insert(info.warnings, 'no OBJ chosen: a placeholder mesh (box and turret) is written')
    end
    mesh.bones = bones
    info.vertices = mesh.n
    info.triangles = table.getn(mesh.idx) / 3
    info.bones = table.getn(bones)
    local x0, y0, z0, x1, y1, z1 = Scm.Bounds(mesh)
    info.bounds = { x0 or 0, y0 or 0, z0 or 0, x1 or 0, y1 or 0, z1 or 0 }
    return mesh, info
end

--- The SCM bytes of the unit mesh: -> data, info | nil, reason.
function Mesh(spec, objText)
    local mesh, info = BuildMesh(spec, objText)
    if not mesh then return nil, info end
    local data, why = Scm.Write(mesh, string.upper(spec.id), { 'FAF Studio unit wizard', 'unit ' .. spec.id })
    if not data then return nil, why end
    info.size = string.len(data)
    return data, info, mesh
end

