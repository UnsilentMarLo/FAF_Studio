local function Num(v)
    if v == math.floor(v) and v > -1000000000 and v < 1000000000 then return string.format('%d', v) end
    local s = string.format('%.6g', v)
    return s
end

local function Str(s) return string.format('%q', s) end

local function IsArray(t)
    local n = table.getn(t)
    if n == 0 then return false end
    local count = 0
    for _ in t do count = count + 1 end
    return count == n
end

local function SortedKeys(t)
    local names = {}
    for k, _ in t do
        if type(k) == 'string' and k ~= '__sound' then table.insert(names, k) end
    end
    table.sort(names)
    return names
end

local function Key(k)
    if string.find(k, '^[A-Za-z_][A-Za-z_0-9]*$') then return k end
    return '[' .. Str(k) .. ']'
end

local function Value(v, indent)
    local kind = type(v)
    if kind == 'number' then return Num(v) end
    if kind == 'boolean' then return v and 'true' or 'false' end
    if kind == 'string' then return Str(v) end
    if kind ~= 'table' then return 'nil' end
    if v.__sound then
        local parts = {}
        for _, k in SortedKeys(v.__sound) do table.insert(parts, k .. ' = ' .. Str(v.__sound[k])) end
        return 'Sound { ' .. table.concat(parts, ', ') .. ' }'
    end
    local pad = indent .. '    '
    if IsArray(v) then
        local simple = true
        for _, x in v do
            if type(x) == 'table' then simple = false end
        end
        if simple then
            local parts = {}
            for _, x in v do table.insert(parts, Value(x, pad)) end
            local line = '{ ' .. table.concat(parts, ', ') .. ' }'
            if string.len(line) < 100 then return line end
        end
        local lines = {}
        for _, x in v do table.insert(lines, pad .. Value(x, pad) .. ',') end
        return '{\n' .. table.concat(lines, '\n') .. '\n' .. indent .. '}'
    end
    local names = SortedKeys(v)
    if table.getn(names) == 0 then return '{}' end
    local lines = {}
    for _, k in names do table.insert(lines, pad .. Key(k) .. ' = ' .. Value(v[k], pad) .. ',') end
    return '{\n' .. table.concat(lines, '\n') .. '\n' .. indent .. '}'
end

