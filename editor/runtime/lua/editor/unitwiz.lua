--- The categories of a spec, sorted: the donor's kind-of-unit categories, the faction and tech categories, the weapon categories, who builds it, and the spec's own additions and removals.
function Categories(spec)
    local d = Donor(spec)
    local set = {}
    for _, c in d.categories or {} do
        if not STRIP[c] and string.sub(c, 1, 7) ~= 'BUILTBY' then set[c] = true end
    end
    set[FactionCat[spec.faction] or 'UEF'] = true
    local tech = spec.tech or 1
    set[tech >= 4 and 'EXPERIMENTAL' or ('TECH' .. tech)] = true
    for _, w in spec.weapons or {} do
        for _, c in KIND_CATS[w.kind] or {} do set[c] = true end
        if spec.template == 'air' and w.kind == 'aa' then set.FIGHTER = true end
    end
    for _, key in spec.buildBy or {} do
        for _, bk in BuildKeys do
            if bk.key == key then set[bk.cat] = true end
        end
    end
    for _, c in spec.catAdd or {} do set[string.upper(c)] = true end
    for _, c in spec.catDel or {} do set[string.upper(c)] = nil end
    local list = {}
    for c, _ in set do table.insert(list, c) end
    table.sort(list)
    return list
end

-- ---- size and skeleton ---------------------------------------------------------------------------------------------------------------------------

--- World size (x, y, z) of the unit's mesh: the imported mesh's bounds, else the donor's scaled to the spec's length.
function Dims(spec)
    local d = Donor(spec)
    local us = d.uniformScale or 0.1
    local b = spec.mesh and spec.mesh.bounds
    if b and spec.mesh.source ~= '' then
        return (b[4] - b[1]) * us, (b[5] - b[2]) * us, (b[6] - b[3]) * us
    end
    local dx, dy, dz = DonorDims(d)
    local f = spec.mesh.length / math.max(0.001, math.max(dx, dz))
    return dx * f, dy * f, dz * f
end

--- Factor from the donor's model units to the spec's: the skeleton and the placeholder are scaled by it.
local function SkeletonScale(spec)
    local d = Donor(spec)
    local dx, dy, dz = DonorDims(d)
    local len = math.max(dx, dz)
    if len < 0.001 then return 1 end
    return (spec.mesh.length > 0 and spec.mesh.length or len) / len
end

--- Bones of the template's skeleton (donor bones, positions scaled to the spec's size). The root keeps the donor's name when the animations of the donor are used (their tracks name the bones).
function TemplateBones(spec)
    local d = Donor(spec)
    local f = SkeletonScale(spec)
    local bones = {}
    for i, row in d.bones do
        local b = { name = row[1], parent = row[2], pos = { row[15] * f, row[16] * f, row[17] * f }, rot = { row[18], row[19], row[20], row[21] } }
        if f > 0.9999 and f < 1.0001 then b.rest = { row[3], row[4], row[5], row[6], row[7], row[8], row[9], row[10], row[11], row[12], row[13], row[14] } end
        if i == 1 and spec.anim == 'none' then b.name = string.upper(spec.id) end
        bones[i] = b
    end
    return bones
end

--- Bone names of the unit (for the blueprint and the validators): the template's, or root + the OBJ's group names.
function BoneNames(spec)
    if spec.mesh.skeleton == 'template' or not spec.mesh.groups then
        local names = {}
        for i, row in Donor(spec).bones do names[i] = row[1] end
        if spec.anim == 'none' then names[1] = string.upper(spec.id) end
        return names
    end
    local names = { string.upper(spec.id) }
    for _, g in spec.mesh.groups do table.insert(names, g) end
    return names
end

--- Bones the first weapon aims with: { yaw, pitch, muzzle, racks = { { RackBone, MuzzleBones } }, turreted } or nil when the skeleton has none.
function WeaponBones(spec)
    local d = Donor(spec)
    if spec.mesh.skeleton == 'template' or not spec.mesh.groups then
        local w = d.weapon
        if not w or not w.muzzle then return nil end
        return { yaw = w.yaw, pitch = w.pitch, muzzle = w.muzzle, racks = w.racks, turreted = w.turreted }
    end
    -- bones made from groups: look for names
    local yaw, pitch, muzzle
    for _, g in spec.mesh.groups do
        local l = string.lower(g)
        if not yaw and (string.find(l, 'turret', 1, true) or string.find(l, 'yaw', 1, true)) then yaw = g end
        if not pitch and (string.find(l, 'barrel', 1, true) or string.find(l, 'pitch', 1, true) or string.find(l, 'gun', 1, true)) then pitch = g end
        if not muzzle and string.find(l, 'muzzle', 1, true) then muzzle = g end
    end
    local b = spec.bones or {}
    yaw, pitch, muzzle = b.yaw or yaw, b.pitch or pitch, b.muzzle or muzzle
    muzzle = muzzle or pitch or yaw
    if not muzzle then return nil end
    return { yaw = yaw, pitch = pitch or yaw, muzzle = muzzle, racks = { { RackBone = pitch or yaw or muzzle, MuzzleBones = { muzzle } } }, turreted = yaw ~= nil }
end

