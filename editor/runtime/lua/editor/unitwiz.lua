    local dir = Folder(spec)
    return {
        { path = dir .. spec.id .. '_unit.bp', kind = 'text', data = BlueprintText(spec, edits), mark = true },
        { path = dir .. spec.id .. '_script.lua', kind = 'text', data = ScriptText(spec), mark = true },
        { path = dir .. spec.id .. '_strings.lua', kind = 'text', data = StringsText(spec), mark = true },
    }
end

local function IsGenerated(text) return text and string.find(text, MARK, 1, true) ~= nil end

--- What the mesh file depends on: the mesh is written again when this changes (the OBJ's file stamp is part of it).
function MeshSignature(spec)
    local m = spec.mesh
    local stamp = (m.source and m.source ~= '') and ed_file_stamp(m.source) or ''
    local wb = WeaponBones(spec)
    return table.concat({ spec.template, spec.faction, tostring(m.length), tostring(m.skeleton), tostring(m.yaw), tostring(m.axis), tostring(m.mirrorX), tostring(m.flipWinding), tostring(m.flipV),
                          tostring(spec.anim), tostring(m.lods), tostring(m.source), tostring(stamp), tostring(wb and wb.yaw), tostring(wb and wb.pitch), tostring(table.getn(spec.weapons or {}) > 0) }, '|')
end

--- Writes the unit's files into the project folder `dir`. Text files are rewritten when they carry the mark (or do not exist); a file without the mark is the user's and is reported, not touched.
--- Binary files are written when the spec names a source for them or when they do not exist yet.
--- -> number of files written, report (list of strings: what was skipped and why), info (mesh info).
function Write(dir, spec, edits, readObj)
    local written, report = 0, {}
    local function Put(rel, data, mark)
        local path = dir .. '/' .. rel
        local old = ed_read_file(path)
        if old and mark and not IsGenerated(old) then
            table.insert(report, rel .. ' exists and was not generated here: left alone')
            return false
        end
        if old == data then return true end
        if not ed_write_file(path, data) then
            table.insert(report, 'cannot write ' .. rel)
            return false
        end
        written = written + 1
        return true
    end
    -- mesh first: its bounds size the collision box and the extents in the blueprint
    local info
    local objText
    if spec.mesh.source and spec.mesh.source ~= '' then
        objText = readObj and readObj(spec.mesh.source) or ed_read_file(spec.mesh.source)
        if not objText then table.insert(report, 'cannot read the OBJ file ' .. spec.mesh.source) end
    end
    local scmPath = Folder(spec) .. spec.id .. '_lod0.scm'
    local have = ed_file_stamp(dir .. '/' .. scmPath)
    local sig = MeshSignature(spec)
    if not have or sig ~= spec.mesh.sig then
        local data, minfo = Mesh(spec, objText)
        if data then
            info = minfo
            if Put(scmPath, data, false) then spec.mesh.sig = sig end
            if (spec.mesh.lods or 1) >= 2 then Put(Folder(spec) .. spec.id .. '_lod1.scm', data, false) end
            if not minfo.placeholder then
                spec.mesh.bounds = minfo.bounds
                spec.mesh.groups = (spec.mesh.skeleton == 'groups') and minfo.groups or nil
            else
                spec.mesh.bounds = nil
                spec.mesh.groups = nil
            end
        else
            table.insert(report, 'mesh: ' .. tostring(minfo))
        end
    end
    for _, f in TextFiles(spec, edits) do Put(f.path, f.data, true) end

    -- textures
    for kind, def in TextureKinds do
        local rel = Folder(spec) .. spec.id .. def.suffix
        local src = spec.textures and spec.textures[kind]
        if (src and src ~= '') or not ed_file_stamp(dir .. '/' .. rel) then
            local px, w, h, placeholder = TextureSource(spec, kind)
            if px then
                local mips = 1
                local size = math.min(w, h)
                while size > 4 do mips = mips + 1 size = size / 2 end
                if not IsPow2(w) or not IsPow2(h) then
                    table.insert(report, def.label .. ': ' .. w .. ' x ' .. h .. ' is not a power of two: written without mip maps')
                    mips = 1
                end
                local ok, why = ed_dds_write(dir .. '/' .. rel, w, h, px, mips)
                if ok then
                    written = written + 1
                    if (spec.mesh.lods or 1) >= 2 and kind ~= 'normal' then
                        local lodRel = Folder(spec) .. spec.id .. '_lod1' .. (kind == 'albedo' and '_albedo.dds' or '_specteam.dds')
                        ed_dds_write(dir .. '/' .. lodRel, w, h, px, mips)
                    end
                else
                    table.insert(report, def.label .. ': ' .. tostring(why))
                end
            else
                table.insert(report, def.label .. ': ' .. tostring(w))
            end
        end
    end
    -- icon: a software preview until the Icons panel renders the real one
    if spec.icon ~= false and not ed_file_stamp(IconPath(dir, spec)) then
        local ok, why = WriteQuickIcon(dir, spec)
        if ok then written = written + 1 else table.insert(report, 'icon: ' .. tostring(why)) end
    end
    return written, report, info
end
