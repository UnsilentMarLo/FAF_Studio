-- ---- helpers -----------------------------------------------------------------------------------------------------------------------------------------

local function Copy(t)
    if type(t) ~= 'table' then return t end
    local c = {}
    for k, v in t do c[k] = Copy(v) end
    return c
end

local function Pick(from, keys)
    local out = {}
    for _, k in keys do
        if from and from[k] ~= nil then out[k] = from[k] end
    end
    return out
end

local function Lower(s) return string.lower(tostring(s or '')) end

--- Index of a value in a list, or nil.
local function IndexOf(list, value)
    for i, v in list do
        if v == value then return i end
    end
    return nil
end

function Template(id)
    for _, t in Templates do
        if t.id == id then return t end
    end
    return nil
end

--- The donor (vanilla unit) of the spec's template and faction.
function Donor(spec)
    local map = Data.Map[spec.template]
    local id = map and map[spec.faction]
    return id and Data.Donors[id], id
end

--- Sound sets the wizard offers: donor unit ids, sorted, with a label.
function SoundSets()
    local list = {}
    for id, d in Data.Donors do
        table.insert(list, { id = id, label = string.upper(id) .. ' (' .. d.faction .. ' ' .. d.template .. ')', faction = d.faction })
    end
    table.sort(list, function(a, b) return a.id < b.id end)
    return list
end

-- ---- ids ---------------------------------------------------------------------------------------------------------------------------------------------

--- A unit id: lower case letters and digits, a letter first, at least 6 characters (the blueprint file name is `<id>_unit.bp`, the id the lower case of it).
function ValidId(id)
    return type(id) == 'string' and string.find(id, '^[a-z][a-z0-9][a-z0-9][a-z0-9][a-z0-9][a-z0-9]+$') ~= nil
end

--- true, or false + the reason. `taken` is a function(id) -> bool for ids of the project (new and derived units).
function CheckId(id, taken)
    if not ValidId(id) then return false, 'a unit id is lower case letters and digits, a letter first, at least 6 characters (like zel0001)' end
    if __blueprints and __blueprints[id] then return false, 'the game has a unit with the id ' .. id end
    if taken and taken(id) then return false, 'the project has a unit with the id ' .. id end
    return true
end

--- A free id: z + faction letter + type letter + four digits (zel0001 ...).
function SuggestId(template, faction, taken)
    local t = Template(template)
    local type_ = (t and t.layer == 'water' and 's') or (t and t.layer == 'air' and 'a') or (t and t.layer == 'structure' and 'b') or 'l'
    local prefix = 'z' .. (FactionLetter[faction] or 'e') .. type_
    for n = 1, 9999 do
        local id = prefix .. string.format('%04d', n)
        if CheckId(id, taken) then return id end
    end
    return prefix .. '0001'
end

-- ---- the spec ------------------------------------------------------------------------------------------------------------------------------------------

function DefaultBuildBy(t, tech)
    if t.builder and t.mobile then
        return { 'factory1', 'factory2', 'factory3' }
    elseif t.mobile then
        local list = {}
        for n = tech, 3 do table.insert(list, 'factory' .. n) end
        if tech >= 4 then list = { 'experimental' } end
        return list
    else
        local list = {}
        if tech <= 1 then table.insert(list, 'commander') elseif tech == 2 then table.insert(list, 'commander2') elseif tech == 3 then table.insert(list, 'commander3') end
        for n = math.min(tech, 3), 3 do table.insert(list, 'engineer' .. n) end
        if tech >= 4 then list = { 'experimental' } end
        return list
    end
end

--- World size (x, y, z) of the donor's mesh: bounds in mesh units times the unit scale.
local function DonorDims(d)
    local us = d.uniformScale or 0.1
    local b = d.bounds
    return (b[4] - b[1]) * us, (b[5] - b[2]) * us, (b[6] - b[3]) * us
end

--- A weapon entry of a spec from the template of its kind: label, kind and the numbers the unit lab and the wizard change.
function NewWeapon(spec, kind, label)
    local base = Data.Weapons[kind] and Data.Weapons[kind][spec.faction]
    local w = { label = label or 'MainGun', kind = kind, name = WeaponKinds[kind] or kind }
    if base then
        w.damage = base.Damage or 10
        w.range = base.MaxRadius or 20
        w.rof = base.RateOfFire or 1
        w.damageRadius = base.DamageRadius or 0
        w.minRange = base.MinRadius or 0
        w.projectile = base.ProjectileId
    else
        w.damage, w.range, w.rof, w.damageRadius, w.minRange = 10, 20, 1, 0, 0
    end
    return w
end

--- A new spec of a template and faction. The numbers start at the donor's (a spec holds the numbers the user can change, the rest comes from the donor at generation time).
function NewSpec(template, faction, id)
    local t = Template(template)
    if not t then return nil, 'no such template' end
    faction = faction or 'UEF'
    local donor, donorId = Donor({ template = template, faction = faction })
    if not donor then return nil, 'no donor for ' .. template .. ' / ' .. faction end
    local spec = {
        id = id, template = template, faction = faction, tech = 1,
        name = 'New ' .. string.lower(t.label), description = t.label,
        catAdd = {}, catDel = {}, buildBy = DefaultBuildBy(t, 1),
        economy = Pick(donor.economy, { 'BuildCostMass', 'BuildCostEnergy', 'BuildTime', 'BuildRate', 'ProductionPerSecondMass', 'ProductionPerSecondEnergy', 'MaintenanceConsumptionPerSecondEnergy' }),
        defense = Pick(donor.defense, { 'MaxHealth', 'RegenRate' }),
        physics = t.mobile and Pick(donor.physics, { 'MaxSpeed', 'MaxAcceleration', 'MaxBrake', 'TurnRate', 'TurnRadius' }) or {},
        intel = Copy(donor.intel),
        sounds = donorId,
        anim = (donor.animationWalk or donor.death) and 'template' or 'none',
        weapons = {},
        mesh = { source = '', axis = 'y_up', yaw = 0, mirrorX = false, flipWinding = false, flipV = true, skeleton = 'template', length = 0, lods = 1 },
        textures = { albedo = '', normal = '', spec = '' },
        icon = true,
    }
    local dx, dy, dz = DonorDims(donor)
    spec.mesh.length = math.floor(math.max(dx, dz) * 100 + 0.5) / 100
    if not spec.defense.MaxHealth then spec.defense.MaxHealth = 100 end
    if not spec.economy.BuildCostMass then spec.economy.BuildCostMass = 50 end
    if not spec.economy.BuildCostEnergy then spec.economy.BuildCostEnergy = 200 end
    if not spec.economy.BuildTime then spec.economy.BuildTime = 100 end
    if t.defaultKind and donor.weapon then
        table.insert(spec.weapons, NewWeapon(spec, t.defaultKind, 'MainGun'))
    end
    if not t.mobile then
        local p = donor.physics or {}
        spec.footprint = { x = p.SkirtSizeX or 1, z = p.SkirtSizeZ or 1 }
    end
    if t.builder then
        spec.buildable = Copy(donor.buildableCategory)
    end
    return spec
end

