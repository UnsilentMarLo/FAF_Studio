local function Sound(t) return { __sound = Copy(t) } end

local function Weapon(spec, w)
    local base = Data.Weapons[w.kind] and Data.Weapons[w.kind][spec.faction] or {}
    local out = {}
    for k, v in base do
        if string.sub(k, 1, 1) ~= '_' then out[k] = Copy(v) end
    end
    if out.Audio then
        local a = {}
        for k, v in out.Audio do a[k] = Sound(v) end
        out.Audio = a
    end
    out.Label = w.label
    out.DisplayName = w.name or w.label
    out.Damage = w.damage
    out.MaxRadius = w.range
    out.MinRadius = w.minRange ~= 0 and w.minRange or nil
    out.RateOfFire = w.rof
    out.DamageRadius = w.damageRadius ~= 0 and w.damageRadius or nil
    if w.projectile and w.projectile ~= '' then out.ProjectileId = w.projectile end
    local bones = WeaponBones(spec)
    if bones then
        out.TurretBoneYaw = bones.yaw
        out.TurretBonePitch = bones.pitch
        out.TurretBoneMuzzle = bones.muzzle
        out.Turreted = bones.turreted and true or false
        if bones.racks and table.getn(bones.racks) > 0 then
            out.RackBones = Copy(bones.racks)
        end
        if not bones.turreted then
            out.TurretBoneYaw, out.TurretBonePitch, out.TurretYaw, out.TurretYawRange, out.TurretYawSpeed = nil, nil, nil, nil, nil
            out.TurretPitch, out.TurretPitchRange, out.TurretPitchSpeed = nil, nil, nil
        end
    else
        out.Turreted = false
        out.TurretBoneYaw, out.TurretBonePitch, out.TurretBoneMuzzle = nil, nil, nil
    end
    return out
end

local function SetPath(bp, path, value)
    local node = bp
    local parts = {}
    for part in string.gfind(path, '[^.]+') do table.insert(parts, tonumber(part) or part) end
    for i = 1, table.getn(parts) - 1 do
        if type(node[parts[i]]) ~= 'table' then node[parts[i]] = {} end
        node = node[parts[i]]
    end
    node[parts[table.getn(parts)]] = value
end

--- The blueprint table of a spec; `edits` = the unit lab's changes { ['Economy.BuildCostMass'] = 5, ['Weapon:MainGun.Damage'] = 9 } are applied last.
function Blueprint(spec, edits)
    local d, donorId = Donor(spec)
    local t = Template(spec.template)
    local id = spec.id
    local bp = {}

    -- sounds
    local set = spec.sounds and Data.Donors[spec.sounds]
    if set and set.audio then
        bp.Audio = {}
        for k, v in set.audio do bp.Audio[k] = Sound(v) end
    end

    bp.AverageDensity = d.averageDensity
    bp.BuildIconSortPriority = d.buildIconSortPriority
    bp.Categories = Categories(spec)
    bp.Description = '<LOC ' .. id .. '_desc>' .. (spec.description or '')

    -- defence
    bp.Defense = {}
    for k, v in d.defense or {} do bp.Defense[k] = v end
    for k, v in spec.defense or {} do bp.Defense[k] = v end
    bp.Defense.MaxHealth = (spec.defense and spec.defense.MaxHealth) or bp.Defense.MaxHealth or 100
    bp.Defense.Health = bp.Defense.MaxHealth

    -- display
    local us = d.uniformScale or 0.1
    local dx, dy, dz = Dims(spec)
    local lods = {}
    local cutoffs = d.lodCutoffs or { 150 }
    local nl = math.max(1, math.min(2, spec.mesh.lods or 1))
    for i = 1, nl do
        local lod = { LODCutoff = cutoffs[i] or cutoffs[table.getn(cutoffs)] or 150 * i, ShaderName = d.shader or 'Unit' }
        if i > 1 then
            lod.AlbedoName = id .. '_lod' .. (i - 1) .. '_albedo.dds'
            lod.SpecularName = id .. '_lod' .. (i - 1) .. '_specteam.dds'
        end
        lods[i] = lod
    end
    bp.Display = { Mesh = { IconFadeInZoom = d.iconFadeInZoom or 130, LODs = lods }, UniformScale = us }
    if spec.anim ~= 'none' then
        if d.animationWalk and t.mobile then
            bp.Display.AnimationWalk = d.animationWalk
            bp.Display.AnimationWalkRate = d.animationWalkRate
        end
        if d.death and table.getn(d.death) > 0 then
            bp.Display.AnimationDeath = {}
            for _, a in d.death do
                table.insert(bp.Display.AnimationDeath, { Animation = a, AnimationRateMax = 1.25, AnimationRateMin = 0.75, Weight = 10 })
            end
        end
    end

    -- economy
    bp.Economy = {}
    for k, v in d.economy or {} do
        if string.sub(k, 1, 8) ~= 'Teleport' then bp.Economy[k] = v end
    end
    for k, v in spec.economy or {} do bp.Economy[k] = v end
    if t.builder and spec.buildable then bp.Economy.BuildableCategory = Copy(spec.buildable) end

    -- general
    bp.General = {}
    for k, v in d.general or {} do bp.General[k] = Copy(v) end
    bp.General.CommandCaps = {}
    for _, cap in d.commandCaps or {} do bp.General.CommandCaps[cap] = true end
    bp.General.FactionName = spec.faction
    bp.General.Icon = d.icon
    bp.General.UnitName = '<LOC ' .. id .. '_name>' .. (spec.name or id)

    bp.Intel = Copy(d.intel)
    for k, v in spec.intel or {} do bp.Intel[k] = v end
    bp.LifeBarHeight, bp.LifeBarOffset, bp.LifeBarSize = d.lifeBarHeight, d.lifeBarOffset, d.lifeBarSize

    -- physics
    bp.Physics = {}
    for k, v in d.physics or {} do bp.Physics[k] = Copy(v) end
    bp.Physics.RaisedPlatforms, bp.Physics.RollOffPoints = nil, nil
    for k, v in spec.physics or {} do bp.Physics[k] = v end
    local function R(v) return math.floor(v * 100 + 0.5) / 100 end
    bp.Physics.MeshExtentsX, bp.Physics.MeshExtentsY, bp.Physics.MeshExtentsZ = R(dx), R(dy), R(dz)
    if not t.mobile and spec.footprint then
        local fx, fz = spec.footprint.x or 1, spec.footprint.z or 1
        bp.Physics.SkirtSizeX, bp.Physics.SkirtSizeZ = fx, fz
        bp.Physics.SkirtOffsetX = -(fx - 1) / 2          -- the skirt centred on the unit (1 -> 0, 2 -> -0.5, 3 -> -1)
        bp.Physics.SkirtOffsetZ = -(fz - 1) / 2
    end
    if t.layer == 'air' and d.air and next(d.air) then bp.Air = Copy(d.air) end
    if d.footprint and next(d.footprint) then bp.Footprint = Copy(d.footprint) end

    -- selection and size
    local sx, sy, sz = R(dx), R(dy), R(dz)
    bp.SizeX, bp.SizeY, bp.SizeZ = sx, sy, sz
    local rx = (d.sizeX and d.sizeX > 0) and (d.selectionSizeX or d.sizeX) / d.sizeX or 0.8
    local rz = (d.sizeZ and d.sizeZ > 0) and (d.selectionSizeZ or d.sizeZ) / d.sizeZ or 0.8
    bp.SelectionSizeX, bp.SelectionSizeZ = R(sx * rx), R(sz * rz)
    bp.SelectionThickness = d.selectionThickness
    bp.StrategicIconName = d.strategicIconName
    bp.StrategicIconSortPriority = d.strategicIconSortPriority
    if d.transport and next(d.transport) then bp.Transport = Copy(d.transport) end
    bp.Veteran = Copy(d.veteran)
    bp.Wreckage = Copy(d.wreckage)
    if d.wreckLayers and table.getn(d.wreckLayers) > 0 then
        bp.Wreckage.WreckageLayers = {}
        for _, l in d.wreckLayers do bp.Wreckage.WreckageLayers[l] = true end
    end

    -- weapons
    if table.getn(spec.weapons or {}) > 0 then
        bp.Weapon = {}
        for _, w in spec.weapons do table.insert(bp.Weapon, Weapon(spec, w)) end
    end

    -- the unit lab's edits
    for key, value in edits or {} do
        local s, e, label, field = string.find(key, '^Weapon:(.-)%.([%w_]+)$')
        if s then
            for _, w in bp.Weapon or {} do
                if w.Label == label then w[field] = value end
            end
        else
            SetPath(bp, key, value)
            if key == 'Defense.MaxHealth' then bp.Defense.Health = value end
        end
    end
    -- the collision box is SizeX / SizeY / SizeZ: the engine raises it to 10 % of the top speed (the speed in the air for aircraft) and to 0.5 in height, and says so in the log; write it that large
    local speed = (bp.Air and bp.Air.MaxAirspeed) or bp.Physics.MaxSpeed
    if t.mobile and speed and speed > 0 then
        local least = math.ceil(speed * 0.1 * 100 + 0.01) / 100
        if (bp.SizeX or 0) < least then bp.SizeX = least end
        if (bp.SizeZ or 0) < least then bp.SizeZ = least end
    end
    if t.mobile and (bp.SizeY or 0) < 0.5 then bp.SizeY = 0.5 end
    return bp
end

