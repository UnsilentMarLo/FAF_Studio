-- The new unit wizard (docs/projects/MOD_UNIT_EDITOR_DESIGN.md, stage S4): a unit with its own id inside a mod project, made from a template and never from a copy of a blueprint.
--
-- A unit is a SPEC (a plain table, kept in the project's edits.lua as NewUnits[id]): template, faction, tech, name, categories, who builds it, economy / defence / physics numbers, weapons,
-- sounds, animations, mesh (an OBJ file or a placeholder), textures. The generators below turn a spec into the files of the project:
--
--   units/<id>/<id>_unit.bp         Blueprint(spec) / BlueprintText(spec)   the unit blueprint (written field by field from the template's numbers, the spec and the unit lab's edits)
--   units/<id>/<id>_script.lua      ScriptText(spec)                        the class from the template (faction + kind), one ClassWeapon per weapon label
--   units/<id>/<id>_strings.lua     StringsText(spec)                       the <LOC> keys of the name and the description (strings_db format)
--   units/<id>/<id>_lod0.scm        Mesh(spec)                              OBJ import (groups -> bones) or a placeholder, skinned to the template's skeleton or one made from the OBJ's groups
--   units/<id>/<id>_albedo.dds ...  Texture(spec, kind)                     imported / converted DDS (any DXT1/3/5 or 32 bit, PNG, BMP, JPEG, TIFF) or a placeholder
--   textures/ui/common/icons/units/<id>_icon.dds                            QuickIcon (software preview of the mesh); the Icons panel replaces it with the engine render
--
-- Templates take pieces of vanilla units BY REFERENCE (unitwizdata.lua, generated by scripts/unitwiz_data.py): the skeleton of the donor unit's mesh, its sound set and animation paths, the numbers a unit of that
-- kind needs (motion, footprint, mesh extents, scale), weapon fields by kind and faction. Nothing is copied wholesale: no categories of the donor that are specific to it, no upgrades, no weapon bones that
-- are not in the unit's skeleton.
--
--   Templates, Factions, TechNames, BuildKeys      the choices      NewSpec(template, faction, id) -> spec      SuggestId(template, faction) -> id      CheckId(id, ignore) -> true | false, reason
--   Files(spec [, edits]) -> list of { path, kind = 'text' | 'binary', data, mark = true | false, generated = true | false }      Write(dir, spec [, edits]) -> n, report
--
-- Lua 5.0 dialect: no `%` (math.mod), no `#` (table.getn), no string.match.

