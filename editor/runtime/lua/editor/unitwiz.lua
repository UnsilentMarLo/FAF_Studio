local FACTION_COLOR = { UEF = { 110, 130, 165 }, Aeon = { 120, 165, 120 }, Cybran = { 165, 100, 85 }, Seraphim = { 190, 175, 120 } }

--- Pixels of a placeholder texture (flat r, g, b, a ... top row first), 64 x 64.
function PlaceholderPixels(kind, faction)
    local n = 64
    local px = {}
    local c = FACTION_COLOR[faction] or { 128, 128, 128 }
    for y = 0, n - 1 do
        for x = 0, n - 1 do
            local i = (y * n + x) * 4
            local checker = (math.mod(math.floor(x / 8) + math.floor(y / 8), 2) == 0) and 1 or 0.86
            if kind == 'albedo' then
                px[i + 1], px[i + 2], px[i + 3], px[i + 4] = math.floor(c[1] * checker), math.floor(c[2] * checker), math.floor(c[3] * checker), 255
            elseif kind == 'normal' then
                -- a flat tangent space normal in the layout of the shipped *_normalsts files (x in alpha and red, y in green, z in blue)
                px[i + 1], px[i + 2], px[i + 3], px[i + 4] = 128, 128, 255, 128
            else
                -- specular in rgb, the team colour mask in alpha (a stripe)
                local stripe = (y >= 24 and y < 40) and 255 or 0
                px[i + 1], px[i + 2], px[i + 3], px[i + 4] = 60, 60, 60, stripe
            end
        end
    end
    return px, n, n
end

local function IsPow2(n)
    if n < 1 or n ~= math.floor(n) then return false end
    while n > 1 do
        if math.mod(n, 2) ~= 0 then return false end
        n = n / 2
    end
    return true
end

--- Reads a texture source (a file on disk or a VFS path) into pixels. -> pixels, w, h | nil, reason. DDS: DXT1 / 3 / 5 / 32 bit; other files through the image reader (PNG, BMP, JPEG, TIFF).
function ReadTexture(path)
    local lower = string.lower(path)
    if string.sub(path, 1, 1) == '/' and ed_vfs_to_disk then
        -- a game path: the disk path of the file (inside an archive for the shipped textures)
        local disk = ed_vfs_to_disk(path) or ed_vfs_to_disk(lower)
        if not disk then return nil, 'the game has no file ' .. path end
        path = disk
    end
    if string.find(lower, '%.dds$') then
        local px, w, h = ed_dds_read(path)
        if not px then return nil, w end
        return px, w, h
    end
    if not ed_img_read then return nil, 'no image reader in this build' end
    local info, why = ed_img_info(path)
    if not info then return nil, why end
    local w, h = info.width, info.height
    if w * h > 4194304 then return nil, 'the picture is ' .. w .. ' x ' .. h .. ': larger than 2048 x 2048' end
    local hasAlpha = info.alpha == 1
    local px = {}
    local rowsPerRead = math.max(1, math.floor(65536 / w))
    for c, ch in { 'r', 'g', 'b', 'a' } do
        if ch ~= 'a' or hasAlpha then
            local field, finfo = ed_img_read(path, { channel = ch })
            if not field then return nil, finfo end
            local y = 0
            while y < h do
                local y1 = math.min(h - 1, y + rowsPerRead - 1)
                local values = ed_field_read(field, 0, y, w - 1, y1)
                if not values then
                    pcall(ed_field_free, field)
                    return nil, 'cannot read the picture channels'
                end
                local k = 0
                for row = y, y1 do
                    for x = 0, w - 1 do
                        k = k + 1
                        local v = values[k] or 0
                        if v < 0 then v = 0 elseif v > 1 then v = 1 end
                        px[(row * w + x) * 4 + c] = math.floor(v * 255 + 0.5)
                    end
                end
                y = y1 + 1
            end
            pcall(ed_field_free, field)
        end
    end
    if not hasAlpha then
        for i = 0, w * h - 1 do px[i * 4 + 4] = 255 end
    end
    return px, w, h
end

--- Pixels of the unit's texture of `kind`: the source file converted, or the placeholder. -> pixels, w, h, placeholder | nil, reason
function TextureSource(spec, kind)
    local src = spec.textures and spec.textures[kind]
    if src and src ~= '' then
        local px, w, h = ReadTexture(src)
        if not px then return nil, w end
        return px, w, h, false
    end
    local px, w, h = PlaceholderPixels(kind, spec.faction)
    return px, w, h, true
end

