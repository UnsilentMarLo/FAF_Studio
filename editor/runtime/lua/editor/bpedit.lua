local function Blueprint(id)
    if Fx.Kind(id) then return Fx.Blueprint(id) end         -- an emitter / beam / trail / projectile blueprint (fxedit.lua)
    local spec = NewUnits[id]
    if spec then
        local c = newCache[id]
        if not c or c.revision ~= Revision then
            c = { revision = Revision, bp = Safe.Call('bpedit.blueprint', Wiz.Blueprint, spec) }          -- without the unit lab's edits: they are the delta over this
            newCache[id] = c
        end
        return c.bp
    end
    local bp = __blueprints and __blueprints[id]
    if bp then return bp end
    local d = Derived and Derived[id]
    return d and __blueprints and __blueprints[d.base]
end

local function Walk(bp, path)
    local node = bp
    for part in string.gfind(path, '[^.]+') do
        if type(node) ~= 'table' then return nil end
        local nextNode = node[part]
        if nextNode == nil and tonumber(part) then nextNode = node[tonumber(part)] end        -- curve keys are array entries
        node = nextNode
    end
    return node
end

local function WeaponByLabel(bp, label)
    for _, w in bp.Weapon or {} do
        if w.Label == label then return w end
    end
    return nil
end

--- The game's value of a field (a number) or nil.
function Base(id, key)
    local bp = Blueprint(id)
    if not bp then return nil end
    local label, field = nil, nil
    local s, e, l, f = string.find(key, '^Weapon:(.-)%.([%w_]+)$')
    local v
    if s then
        local w = WeaponByLabel(bp, l)
        v = w and w[f]
    else
        v = Walk(bp, key)
    end
    if type(v) == 'number' then return v end
    return nil
end

function Get(id, key)
    local e = Edits[id]
    if e and e[key] ~= nil then return e[key] end
    return Base(id, key)
end

local function Range(base, dec)
    local step = (dec == 0) and 1 or math.pow(10, -dec)
    if dec >= 2 then step = 0.05 end
    local max = math.max(10, base * 4)
    if dec == 0 then max = math.ceil(max / 10) * 10 end
    return 0, max, step
end

--- The editable fields of a unit, only the ones its blueprint has (a number).
function Fields(id)
    if Fx.Kind(id) then return Fx.Fields(id) end
    local bp = Blueprint(id)
    local list = {}
    if not bp then return list end
    for _, f in UNIT_FIELDS do
        local base = Base(id, f[1])
        if base and base ~= 0 then
            local min, max, step = Range(base, f[4])
            table.insert(list, { key = f[1], label = f[2], group = f[3], base = base, min = min, max = max, step = step, dec = f[4] })
        end
    end
    for _, w in bp.Weapon or {} do
        if w.Label and not w.DummyWeapon then
            for _, f in WEAPON_FIELDS do
                local key = 'Weapon:' .. w.Label .. '.' .. f[1]
                local base = Base(id, key)
                if base and (base ~= 0 or f[1] == 'MinRadius') then
                    local min, max, step = Range(base, f[3])
                    table.insert(list, { key = key, label = w.Label .. ': ' .. f[2], group = 'Weapon ' .. w.Label, base = base, min = min, max = max, step = step, dec = f[3] })
                end
            end
        end
    end
    return list
end

-- ---- edits -----------------------------------------------------------------------------------------------------------------------------------------

local function Copy(t)
    if type(t) ~= 'table' then return t end
    local c = {}
    for k, v in t do c[k] = Copy(v) end
    return c
end

--- The project's state for an undo entry: the edits (cheap, every slider tick) or, `wide`, the edits, the new units and the derived units.
local function Snapshot(wide)
    local snap = { Edits = Copy(Edits) }
    if wide then
        snap.NewUnits = Copy(NewUnits)
        snap.Derived = Copy(Derived)
    end
    return snap
end

local function Restore(snap)
    Edits = Copy(snap.Edits)
    if snap.NewUnits then
        NewUnits = Copy(snap.NewUnits)
        Derived = Copy(snap.Derived)
        newCache = {}
        specSeen = {}
        for id, spec in NewUnits do specSeen[id] = Copy(spec) end
    end
    Revision = Revision + 1
end

local function Now()
    local clock = rawget(_G, 'GetSystemTimeSeconds')
    return clock and clock() or 0
end

--- Pushes the undo entry of a change that is done: `before` is the Snapshot taken before it. A change with a mergeKey folds into the entry on top of the history when that one has the same key and
--- is from the same project and less than a second old (one slider drag is one step).
local function Record(label, before, mergeKey, wide)
    local gen = Generation
    local top = mergeKey and History.Top and History.Top()
    local now = Now()
    if top and top.mergeKey == mergeKey and top.gen == gen and top.snapshot and top.wide == wide and now - (top.at or 0) < 1 then
        top.snapshot.after = Snapshot(wide)
        top.at = now
        return true
    end
    local snap = { before = before, after = Snapshot(wide) }
    local function Stale()
        WARN('EDITOR bpedit: "' .. label .. '" belongs to a project that is not open any more: nothing undone')
    end
    History.Push({ label = label, mergeKey = mergeKey, snapshot = snap, gen = gen, wide = wide, at = now,
                   undo = function() if gen ~= Generation then return Stale() end Restore(snap.before) end,
                   redo = function() if gen ~= Generation then return Stale() end Restore(snap.after) end })
    return true
end

--- Runs a change as one undo entry. A function that raises leaves the project as it was (the snapshot is put back) and the error is reported: -> false, message. `wide`: the change touches
--- new / derived units too.
local function Do(label, fn, mergeKey, wide)
    local before = Snapshot(wide)
    local ok, err = pcall(fn)
    if not ok then
        Restore(before)
        Safe.Report('bpedit.' .. string.gsub(label, ' .*', ''), err)
        return false, tostring(err)
    end
    Revision = Revision + 1
    return Record(label, before, mergeKey, wide)
end

function Set(id, key, value, merge)
    local base = Base(id, key)
    return Do('edit ' .. id .. ' ' .. key, function()
        Edits[id] = Edits[id] or {}
        if base ~= nil and math.abs(value - base) < 0.0000001 then
            Edits[id][key] = nil           -- back at the game's value: no delta
        else
            Edits[id][key] = value
        end
        local any = false
        for _ in Edits[id] do any = true end
        if not any then Edits[id] = nil end
    end, merge and ('bp' .. id .. key) or nil)
end

function Revert(id, key)
    if not (Edits[id] and Edits[id][key] ~= nil) then return false end
    return Do('revert ' .. id .. ' ' .. key, function()
        Edits[id][key] = nil
        local any = false
        for _ in Edits[id] do any = true end
        if not any then Edits[id] = nil end
    end)
end

function RevertAll(id)
    if not Edits[id] then return false end
    return Do('revert ' .. id, function() Edits[id] = nil end)
end

function Edited()
    local list = {}
    for id, _ in Edits do table.insert(list, id) end
    table.sort(list)
    return list
end

--- True for a unit made by the new unit wizard.
function IsNew(id) return NewUnits[id] ~= nil end

--- Ids of the new units, sorted.
function NewIds()
    local list = {}
    for id, _ in NewUnits do table.insert(list, id) end
    table.sort(list)
    return list
end

local function IdTaken(id)
    return NewUnits[id] ~= nil or Derived[id] ~= nil
end

--- Adds a unit spec made by unitwiz.NewSpec (one undo step). -> true | nil + reason
function AddNew(spec)
    if not Project then return nil, 'no project open' end
    local ok, why = Wiz.CheckId(spec.id, IdTaken)
    if not ok then return nil, why end
    local done, err = Do('add unit ' .. spec.id, function() NewUnits[spec.id] = spec end, nil, true)
    if not done then return nil, err end
    specSeen[spec.id] = Copy(spec)
    return true
end

local function SameValue(a, b)
    if type(a) ~= type(b) then return false end
    if type(a) ~= 'table' then return a == b end
    for k, v in a do if not SameValue(v, b[k]) then return false end end
    for k, _ in b do if a[k] == nil then return false end end
    return true
end

--- Call after changing a spec in place (the wizard does): the generated blueprint is made again, and the change since the last call is one undo step (changes within a second of each
--- other on the same unit share a step).
function TouchNew(id)
    newCache[id] = nil
    Revision = Revision + 1
    local spec = NewUnits[id]
    local seen = specSeen[id]
    if spec and seen and not SameValue(spec, seen) then
        local before = Snapshot(true)
        before.NewUnits[id] = Copy(seen)
        specSeen[id] = Copy(spec)
        Record('edit unit ' .. id, before, 'newunit' .. id, true)
    elseif spec and not seen then
        specSeen[id] = Copy(spec)
    end
end

--- Removes a new unit with its edits (one undo step; the files already written stay on disk).
function RemoveNew(id)
    if not NewUnits[id] then return false end
    local ok = Do('remove unit ' .. id, function()
        NewUnits[id] = nil
        Edits[id] = nil
        newCache[id] = nil
        specSeen[id] = nil
    end, nil, true)
    return ok and true or false
end

--- A free id for a new unit.
function SuggestNewId(template, faction)
    return Wiz.SuggestId(template, faction, IdTaken)
end

-- ---- the merge blueprint ---------------------------------------------------------------------------------------------------------------------------

local function Number(v)
    if v == math.floor(v) and v > -1000000000 and v < 1000000000 then return string.format('%d', v) end
    return string.format('%.4f', v)
end

--- The fields of a unit's delta as Lua text (nested tables, then ModWeapon), every line indented by `indent`.
local function Body(id, indent)
    local e = Edits[id]
    if not e then return nil end
    local nested, weapons, order = {}, {}, {}
    local keys = {}
    for k, _ in e do table.insert(keys, k) end
    table.sort(keys)
    for _, key in keys do
        local s, _, label, field = string.find(key, '^Weapon:(.-)%.([%w_]+)$')
        if s then
            if not weapons[label] then weapons[label] = {} table.insert(order, label) end
            weapons[label][field] = e[key]
        else
            local node = nested
            local parts = {}
            for part in string.gfind(key, '[^.]+') do table.insert(parts, tonumber(part) or part) end
            for i = 1, table.getn(parts) - 1 do
                node[parts[i]] = node[parts[i]] or {}
                node = node[parts[i]]
            end
            node[parts[table.getn(parts)]] = e[key]
        end
    end
    local function Dump(t, indent)
        local names = {}
        for k, _ in t do table.insert(names, k) end
        table.sort(names, function(a, b)
            if type(a) == type(b) then return a < b end
            return type(a) == 'number'
        end)
        local lines = {}
        for _, k in names do
            local v = t[k]
            local name = type(k) == 'number' and ('[' .. k .. ']') or k
            if type(v) == 'table' then
                table.insert(lines, indent .. name .. ' = {\n' .. Dump(v, indent .. '    ') .. indent .. '},\n')
            else
                table.insert(lines, indent .. name .. ' = ' .. Number(v) .. ',\n')
            end
        end
        return table.concat(lines)
    end
    local out = { Dump(nested, indent) }
    table.sort(order)
    if table.getn(order) > 0 then
        table.insert(out, indent .. 'ModWeapon = {\n')
        for _, label in order do
            table.insert(out, indent .. '    {\n' .. indent .. "        MergeLabel = '" .. label .. "',\n" .. Dump(weapons[label], indent .. '        ') .. indent .. '    },\n')
        end
        table.insert(out, indent .. '},\n')
    end
    return table.concat(out)
end

--- The text of a unit's merge blueprint (delta only).
function MergeText(id)
    local body = Body(id, '    ')
    if not body then return nil end
    if Fx.Kind(id) then
        -- the game names these blueprints by the file they come from, so the merge file says which one it changes (Source)
        return MARK .. '\n' .. Fx.Header(id) .. " {\n    Merge = true,\n    Source = '" .. id .. "',\n" .. body .. '}\n'
    end
    return MARK .. "\nUnitBlueprint {\n    Merge = true,\n    BlueprintId = '" .. id .. "',\n" .. body .. '}\n'
end

-- ---- derived units -----------------------------------------------------------------------------------------------------------------------------------
-- A new unit made from an existing one without copying any file: the project's blueprint hook (hook/lua/system/Blueprints.lua, chained ModBlueprints) deep-copies the base unit's blueprint
-- under the new id and applies the unit's edits (and its name and description) to the copy. Mesh, script, sounds and the build menu stay the base unit's.

Derived = {}        -- id -> { base, name, description }

local function ValidId(id)
    return type(id) == 'string' and string.find(id, '^[a-z][a-z0-9]+$') ~= nil and string.len(id) >= 6
end

function AddDerived(id, base, name, description)
    if not Project then return nil, 'no project open' end
    if not ValidId(id) then return nil, 'a unit id is lower case letters and digits, at least 6 (like zml0001)' end
    if Derived[id] or NewUnits[id] or (__blueprints and __blueprints[id]) then return nil, 'there is a unit with that id already' end
    if not (__blueprints and __blueprints[base]) then return nil, 'the base unit does not exist' end
    local ok, err = Do('add derived unit ' .. id, function() Derived[id] = { base = base, name = name or '', description = description or '' } end, nil, true)
    if not ok then return nil, err end
    return true
end

function RemoveDerived(id)
    if not Derived[id] then return false end
    local ok = Do('remove derived unit ' .. id, function()
        Derived[id] = nil
        Edits[id] = nil
    end, nil, true)
    return ok and true or false
end

--- The text of the project's blueprint hook for every derived unit.
function HookText()
    local ids = {}
    for id, _ in Derived do table.insert(ids, id) end
    table.sort(ids)
    local out = { MARK .. '\n', '-- Derived units: copies of an existing blueprint with changed fields (FAF Studio unit lab).\n', 'do\n', '    local oldModBlueprints = ModBlueprints\n\n',
                  '    function ModBlueprints(all_bps)\n        oldModBlueprints(all_bps)\n\n',
                  '        local function Derive(id, base, name, description, delta, weapons)\n',
                  '            local source = all_bps.Unit[base]\n',
                  "            if not source then WARN('derived unit ' .. id .. ': base unit ' .. base .. ' not found') return end\n",
                  '            local bp = table.deepcopy(source)\n',
                  '            bp.BlueprintId = id\n',
                  '            bp = BlueprintMerged(bp, delta)\n',
                  '            for _, w in weapons do MergeWeaponByLabel(bp, w.MergeLabel, nil, w) end\n',
                  "            if name ~= '' then bp.General = bp.General or {} bp.General.UnitName = name end\n",
                  "            if description ~= '' then bp.Description = description end\n",
                  '            all_bps.Unit[id] = bp\n',
                  '        end\n\n' }
    local function Q(t) return string.format('%q', t or '') end
    for _, id in ids do
        local d = Derived[id]
        local indent = '                '
        local body = Body(id, indent) or ''
        -- the nested fields go into the delta table, the ModWeapon entries into the weapon list
        local at = string.find(body, indent .. 'ModWeapon = {', 1, true)
        local delta = at and string.sub(body, 1, at - 1) or body
        local list = ''
        if at then
            list = string.sub(body, at)
            list = string.gsub(list, '^%s*ModWeapon = {\n', '')
            list = string.gsub(list, '\n%s*},\n$', '\n')
        end
        table.insert(out, '        Derive(' .. Q(id) .. ', ' .. Q(d.base) .. ', ' .. Q(d.name) .. ', ' .. Q(d.description) .. ', {\n' .. delta .. '            }, {\n' .. list .. '            })\n')
    end
    table.insert(out, '    end\nend\n')
    return table.concat(out)
end

-- ---- projects --------------------------------------------------------------------------------------------------------------------------------------

--- Names of the projects (the index file `projects.txt` in the project root lists them).
function Projects()
    local list = {}
    local text = ed_read_file(ROOT .. '/projects.txt')
    for line in string.gfind(text or '', '[^\r\n]+') do
        if ed_file_stamp(ROOT .. '/' .. line .. '/mod_info.lua') then table.insert(list, line) end
    end
    table.sort(list)
    return list
end

local function Index(name)
    for _, n in Projects() do if n == name then return end end
    local list = Projects()
    table.insert(list, name)
    ed_write_file(ROOT .. '/projects.txt', table.concat(list, '\n') .. '\n')
end

local function Dir(name) return ROOT .. '/' .. name end

--- A uid for a new project: 8-4-4-4-12 hex digits, 'ED' first so they are recognisable, from the clock and the name; one the game knows already is skipped.
local function NewUid(name)
    local a, b = 1, 0
    for i = 1, string.len(name) do
        a = math.mod(a + string.byte(name, i), 65521)
        b = math.mod(b + a, 65521)
    end
    math.randomseed(math.floor(Now() * 1000) + a * 65536 + b)
    local known = {}
    local ok, all = pcall(function() return import('/lua/mods.lua').AllMods() end)
    if ok and type(all) == 'table' then for uid, _ in all do known[string.lower(tostring(uid))] = true end end
    local uid
    repeat
        uid = string.format('ED%06X-%04X-4D57-%04X-%04X%04X%04X', math.random(0, 16777215), math.random(0, 65535), 32768 + math.random(0, 16383), math.random(0, 65535), math.random(0, 65535), math.random(0, 65535))
    until not known[string.lower(uid)]
    return uid
end

local function ModInfo(name, uid, version)
    return 'name = ' .. string.format('%q', name) .. '\nversion = ' .. (version or 1) .. '\nauthor = "FAF Studio"\ncopyright = "mod project"\n' ..
           'description = "Mod project made in the FAF Studio unit lab: merge blueprints, delta only."\nuid = "' .. uid .. '"\nexclusive = false\nui_only = false\nselectable = true\nenabled = true\n'
end

--- uid and version of a project's mod_info.lua (read in an empty environment).
local function ReadModInfo(dir)
    local env = SafeLoad.File(dir .. '/mod_info.lua', { name = 'mod_info.lua', keepBad = false })
    if env and type(env.uid) == 'string' then return env.uid, tonumber(env.version) or 1 end
    return nil, 1
end

local function StartProject(name)
    Project = name
    Generation = Generation + 1
    Damaged = false
    Blocked = {}
    Edits = {}
    Derived = {}
    NewUnits = {}
    newCache = {}
    specSeen = {}
    Revision = Revision + 1
end

--- Creates the project folder with its mod_info.lua and mounts it. true | nil + reason.
function Create(name)
    if not name or name == '' or string.find(name, '[^%w_ -]') then return nil, 'project names take letters, digits, space, - and _' end
    local dir = Dir(name)
    if ed_file_stamp(dir .. '/mod_info.lua') then return nil, 'there is a project with that name already' end
    local uid = NewUid(name)
    if not ed_write_file(dir .. '/mod_info.lua', ModInfo(name, uid, 1)) then return nil, 'cannot write the project folder' end
    ed_vfs_mount(dir, '/mods/' .. name)
    Safe.Try('bpedit.mods-cache', function() import('/lua/mods.lua').ClearCache() end)       -- the engine lists mods once: look again
    Index(name)
    StartProject(name)
    Uid = uid
    return true
end

local function Sanitize(env)
    local edits, derived, new = {}, {}, {}
    for id, e in env.Edits or {} do
        if type(id) == 'string' and type(e) == 'table' then
            local row = {}
            for key, v in e do
                if type(key) == 'string' and type(v) == 'number' then row[key] = v end
            end
            edits[id] = row
        end
    end
    for id, d in env.Derived or {} do
        if type(id) == 'string' and type(d) == 'table' and type(d.base) == 'string' then
            derived[id] = { base = d.base, name = type(d.name) == 'string' and d.name or '', description = type(d.description) == 'string' and d.description or '' }
        end
    end
    for id, spec in env.NewUnits or {} do
        if type(id) == 'string' and type(spec) == 'table' and spec.id == id then new[id] = Copy(spec) end
    end
    return edits, derived, new
end

local EDITS_OPTIONS = { name = 'edits.lua', current = EDITS_VERSION, schema = { Edits = 'table', Derived = 'table', NewUnits = 'table' }, migrate = {} }

--- Opens a project (reads edits.lua). A file that cannot be read is tried again as edits.lua.bak (the copy before the last write); when that fails too the project opens empty and is
--- `Damaged`: -> true, warning | nil + reason.
function Open(name)
    local dir = Dir(name)
    if not ed_file_stamp(dir .. '/mod_info.lua') then return nil, 'no such project' end
    StartProject(name)
    Uid = ReadModInfo(dir) or false
    local warning
    if ed_file_stamp(dir .. '/edits.lua') then
        local env, why = SafeLoad.File(dir .. '/edits.lua', EDITS_OPTIONS)
        if not env then
            warning = 'edits.lua could not be read (' .. tostring(why) .. ')'
            local bak
            bak, why = SafeLoad.File(dir .. '/edits.lua.bak', { name = 'edits.lua.bak', current = EDITS_VERSION, schema = EDITS_OPTIONS.schema, keepBad = false })
            if bak then
                env = bak
                warning = warning .. '; the copy before the last write (edits.lua.bak) was opened instead'
            end
        end
        if env then
            Edits, Derived, NewUnits = Sanitize(env)
        else
            Damaged = warning .. ': the project opened empty. The original is kept as edits.lua.bad; Write will not replace edits.lua until you decide (Write(true))'
        end
    end
    for id, spec in NewUnits do specSeen[id] = Copy(spec) end
    if warning then WARN('EDITOR bpedit: project ' .. name .. ': ' .. warning) end
    Revision = Revision + 1
    return true, warning
end

--- Where the merge blueprint of an edited id goes: units/<id>/<id>_unit.bp, or the game's own path for an emitter / beam / trail / projectile.
function FilePath(dir, id)
    if Fx.Kind(id) then return dir .. string.lower(id) end
    return dir .. '/units/' .. id .. '/' .. id .. '_unit.bp'
end

--- Writes `data` to `path` and reads it back. When the old file was readable it is kept as `<path>.bak` first and put back if the new one does not read back as written.
--- (No rename from Lua: the target is overwritten in place, but there is a good copy on disk at every moment and Open falls back to it.) -> true | nil + reason
local function SafeWrite(path, data, validate)
    if validate then
        local good, why = validate(data)
        if not good then return nil, 'refused to write ' .. path .. ': ' .. tostring(why) end
    end
    local old = ed_read_file(path)
    if old == data then return true end
    if old and old ~= '' and (not validate or validate(old)) then
        if not ed_write_file(path .. '.bak', old) then return nil, 'cannot write the backup ' .. path .. '.bak' end
    end
    if not ed_write_file(path, data) or ed_read_file(path) ~= data then
        if old then ed_write_file(path, old) end
        return nil, 'cannot write ' .. path
    end
    return true
end

local function ValidEdits(text)
    local env, why = SafeLoad.Text(text, { name = 'edits.lua', salvage = false, current = EDITS_VERSION, schema = EDITS_OPTIONS.schema })
    if not env then return false, why end
    return true
end

local function ValidLua(text)
    local f, err = loadstring(text)
    if not f then return false, err end
    return true
end

--- Writes edits.lua and one merge blueprint per edited unit; a file that is there without the generated mark is not touched. -> number of files, or nil + reason.
--- `go` writes although edits.lua of the project could not be read (Damaged): the unreadable file is replaced then (the .bad copy stays).
--- The generated text files are compiled first: one that does not compile is not written (the old file stays), it is listed in `Blocked` and `Report`.
function Write(go)
    if not Project then return nil, 'no project open' end
    if Damaged and not go then return nil, tostring(Damaged) end
    local dir = Dir(Project)
    local n = 0
    Blocked = {}
    Report = {}
    local chunk = Ser.Chunk({ { 'version', EDITS_VERSION }, { 'Edits', Edits }, { 'Derived', Derived }, { 'NewUnits', NewUnits } })
    local ok, why = SafeWrite(dir .. '/edits.lua', chunk, ValidEdits)
    if not ok then return nil, why end
    Damaged = false
    for _, id in Edited() do
        if not Derived[id] and not NewUnits[id] then
            local path = FilePath(dir, id)
            local old = ed_read_file(path)
            if old and not string.find(old, MARK, 1, true) then return nil, path .. ' exists and was not generated here: left alone' end
            local text = MergeText(id)
            local good, bad = ValidLua(text)
            if not good then
                table.insert(Blocked, path)
                table.insert(Report, id .. ': the merge blueprint does not compile (' .. tostring(bad) .. '): not written')
            elseif not ed_write_file(path, text) then
                return nil, 'cannot write ' .. path
            else
                n = n + 1
            end
        end
    end
    -- the new units: blueprint, script, strings, mesh, textures, icon (unitwiz.lua); the unit lab's edits go into the blueprint
    local Check = import('/lua/editor/unitcheck.lua')
    for _, id in NewIds() do
        local problems = Check.PreWrite(NewUnits[id], Edits[id])
        if table.getn(problems) > 0 then
            table.insert(Blocked, id)
            for _, p in problems do table.insert(Report, id .. ': NOT WRITTEN: ' .. p) end
        else
            local good, count, report = pcall(Wiz.Write, dir, NewUnits[id], Edits[id])
            if not good then
                Safe.Report('bpedit.unitwiz', count)
                table.insert(Blocked, id)
                table.insert(Report, id .. ': the wizard could not write the unit: ' .. tostring(count))
            else
                n = n + count
                for _, line in report do table.insert(Report, id .. ': ' .. line) end
            end
        end
    end
    -- the blueprint hook with the derived units (kept in step: emptied when no derived unit is left)
    local hookPath = dir .. '/hook/lua/system/Blueprints.lua'
    local oldHook = ed_read_file(hookPath)
    local any = false
    for _ in Derived do any = true end
    if any then
        if oldHook and not string.find(oldHook, MARK, 1, true) then return nil, hookPath .. ' exists and was not generated here: left alone' end
        local text = HookText()
        local good, bad = ValidLua(text)
        if not good then
            table.insert(Blocked, hookPath)
            table.insert(Report, 'the blueprint hook for the derived units does not compile (' .. tostring(bad) .. '): not written')
        elseif not ed_write_file(hookPath, text) then
            return nil, 'cannot write ' .. hookPath
        else
            n = n + 1
        end
    elseif oldHook and string.find(oldHook, MARK, 1, true) then
        ed_write_file(hookPath, MARK .. '\n-- (no derived units)\n')
    end
    -- the project's version counts the writes that changed something (mod_info.lua keeps the rest of the file as it is)
    if n > 0 then
        local infoPath = dir .. '/mod_info.lua'
        local info = ed_read_file(infoPath)
        if info then
            local uid, version = ReadModInfo(dir)
            local text, count = string.gsub(info, 'version%s*=%s*%d+', 'version = ' .. ((version or 1) + 1), 1)
            if count == 1 then ed_write_file(infoPath, text) end
        end
    end
    Revision = Revision + 1          -- the files on disk changed (the project checks look again)
    if table.getn(Blocked) > 0 then
        WARN('EDITOR bpedit: ' .. table.getn(Blocked) .. ' file(s) were not written because they would not load: ' .. table.concat(Report, '; '))
    end
    return n
end

--- Problems of the project.
function Check()
    local list = {}
    if not Project then return list end
    if Damaged then table.insert(list, { sev = 'E', text = 'edits.lua of this project could not be read: ' .. tostring(Damaged) }) end
    for _, b in Blocked do table.insert(list, { sev = 'E', text = 'not written because it would not load: ' .. tostring(b) .. ' (see the Console)' }) end
    for id, spec in NewUnits do
        local c = import('/lua/editor/unitcheck.lua')
        local good, found = pcall(c.Check, id, spec, Edits[id])
        if good then
            for _, p in found do table.insert(list, p) end
        else
            Safe.Report('bpedit.check', found)
            table.insert(list, { sev = 'E', text = id .. ': the unit could not be checked, its spec is damaged (' .. tostring(found) .. ')' })
        end
    end
    for id, d in Derived do
        if not (__blueprints and __blueprints[d.base]) then table.insert(list, { sev = 'E', text = 'derived unit ' .. id .. ': base unit ' .. tostring(d.base) .. ' is not in the game' }) end
    end
    local okHook, hookFn, hookErr = pcall(loadstring, HookText())
    if not okHook then hookErr = hookFn hookFn = nil end
    if not hookFn then table.insert(list, { sev = 'E', text = 'the generated blueprint hook does not compile: ' .. tostring(hookErr) }) end
    for _, id in Edited() do
        if not Blueprint(id) then
            table.insert(list, { sev = 'E', text = (Fx.Kind(id) and 'blueprint ' or 'unit ') .. id .. ' is not in the game any more' })
        else
            local known = {}
            for _, f in Fields(id) do known[f.key] = true end
            for key, v in Edits[id] do
                if not known[key] then table.insert(list, { sev = 'W', text = id .. ': ' .. key .. ' is not a field of this unit (edit kept, not written)' }) end
                if v < 0 and not Fx.Kind(id) then table.insert(list, { sev = 'W', text = id .. ': ' .. key .. ' is negative' }) end
            end
        end
    end
    return list
end
