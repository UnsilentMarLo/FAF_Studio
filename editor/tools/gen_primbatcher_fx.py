#!/usr/bin/env python3
"""Generates editor/runtime/override/effects/primbatcher.fx = FAF's primbatcher.fx + the editor text techniques.

    python editor/tools/gen_primbatcher_fx.py            # write the file
    python editor/tools/gen_primbatcher_fx.py --check    # exit 1 if the generated file is stale (FAF's file or the block changed)

editor/runtime/override is mounted first on the VFS root by init_editor.lua (mounts earlier in the list win), so /effects/primbatcher.fx shadows FAF's file in the editor only. The header records the
SHA-256 of FAF's file: when FAF changes primbatcher.fx, --check fails and the file is regenerated from the new base.
"""
import hashlib
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import studio_paths as P  # noqa: E402
BASE = os.path.join(P.FAF_REPO, "effects", "primbatcher.fx")      # FAF's own file (a FAForever/fa checkout: FAF_STUDIO_FAF_REPO)
PART = os.path.join(ROOT, "editor", "runtime", "override", "effects", "edtext_techniques.fx.part")
OUT = os.path.join(ROOT, "editor", "runtime", "override", "effects", "primbatcher.fx")


def build():
    base = open(BASE, "rb").read()
    part = open(PART, "rb").read()
    digest = hashlib.sha256(base).hexdigest()
    header = ("// GENERATED by editor/tools/gen_primbatcher_fx.py: do not edit.\n"
              "// base: faf_repo/fa/effects/primbatcher.fx sha256 " + digest + "\n"
              "// block: editor/runtime/override/effects/edtext_techniques.fx.part\n").encode("ascii")
    return header + base + part


def main(argv):
    data = build()
    if "--check" in argv:
        current = open(OUT, "rb").read() if os.path.exists(OUT) else b""
        if current != data:
            print("stale: run python editor/tools/gen_primbatcher_fx.py")
            return 1
        print("up to date")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "wb").write(data)
    print("wrote", OUT, len(data), "bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
