#!/usr/bin/env python3
"""Generates editor/runtime/override/effects/terrain.fx = FAF's terrain.fx with one change: the terrain NORMAL passes weigh the strata the way the albedo passes do.

    python editor/tools/gen_terrain_fx.py            # write the file
    python editor/tools/gen_terrain_fx.py --check    # exit 1 if the generated file is stale (FAF's file or the patch changed)

Why: a paint mask byte m is read by the albedo passes (TerrainPS, TerrainAlbedoXP) as saturate(2 * m / 255 - 1): bytes up to 127 mean "nothing", 255 "fully this layer". The normal passes
(TerrainNormalsPS, TerrainNormalsXP) read the same bytes as saturate(m / 255), so a cell the albedo shows nothing of (a byte of 128 and up that is almost nothing, the soft edge of an erased
brush stroke, a faint paint) still got half of the layer's normal map: the normal map detail of a layer stayed visible where the layer was erased or barely painted. The editor shows what the
mask says: both passes use saturate(2 * m - 1). (The game itself still renders FAF's file: only the editor's VFS shadows it, editor/runtime/override is mounted first, init_editor.lua.)
The header records the SHA-256 of FAF's file: when FAF changes terrain.fx, --check fails and the file is regenerated from the new base (a replacement that no longer matches stops the script).
"""
import hashlib
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import studio_paths as P  # noqa: E402
BASE = os.path.join(P.FAF_REPO, "effects", "terrain.fx")      # FAF's own file (a FAForever/fa checkout: FAF_STUDIO_FAF_REPO)
OUT = os.path.join(ROOT, "editor", "runtime", "override", "effects", "terrain.fx")

# (text in FAF's file, replacement); every one must occur exactly once
PATCHES = [
    ("float4 mask = saturate(tex2D( UtilitySamplerA, inV.mTexWT * TerrainScale));\n\n    float4 lowerNormal",
     "float4 mask = saturate(tex2D( UtilitySamplerA, inV.mTexWT * TerrainScale) * 2 - 1);   // EDITOR: the albedo's weight\n\n    float4 lowerNormal"),
    ("float4 mask0 = saturate(tex2D(UtilitySamplerA,pixel.mTexWT*TerrainScale));\n    float4 mask1 = saturate(tex2D(UtilitySamplerB,pixel.mTexWT*TerrainScale));\n\n    float4 lowerNormal",
     "float4 mask0 = saturate(tex2D(UtilitySamplerA,pixel.mTexWT*TerrainScale)*2-1);   // EDITOR: the albedo's weight\n    float4 mask1 = saturate(tex2D(UtilitySamplerB,pixel.mTexWT*TerrainScale)*2-1);\n\n    float4 lowerNormal"),
]


def build():
    base = open(BASE, "rb").read()
    text = base.decode("latin-1").replace("\r\n", "\n")
    for old, new in PATCHES:
        if text.count(old) != 1:
            raise SystemExit("patch does not match FAF's terrain.fx exactly once (%d): %r" % (text.count(old), old[:60]))
        text = text.replace(old, new)
    digest = hashlib.sha256(base).hexdigest()
    header = ("// GENERATED by editor/tools/gen_terrain_fx.py: do not edit.\n"
              "// base: faf_repo/fa/effects/terrain.fx sha256 " + digest + "\n"
              "// change: the normal passes read the strata masks as saturate(2 * m - 1) like the albedo passes do\n")
    return (header + text).encode("latin-1")


def main(argv):
    data = build()
    if "--check" in argv:
        current = open(OUT, "rb").read() if os.path.exists(OUT) else b""
        if current != data:
            print("stale: run python editor/tools/gen_terrain_fx.py")
            return 1
        print("up to date")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "wb").write(data)
    print("wrote", OUT, len(data), "bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
