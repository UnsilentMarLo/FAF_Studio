#!/usr/bin/env python
"""The functions a generated mission script may call, taken from the game's own Lua.

    python scripts/editor_mission_api.py             writes editor/runtime/lua/editor/data/faf_mission_api.lua from the FAF client's lua.nx2
    python scripts/editor_mission_api.py --check     fails when (a) the committed table is out of date with the game's Lua (only when the game is installed) or
                                                     (b) the mission compiler (mission.lua, missionplat.lua, mbase.lua) names a ScenarioFramework / Objectives /
                                                     ScenarioUtils / Cinematics function that the table does not have (always)

The table has one entry per module the emitters call into: `Name = <number of parameters>` (-1 = variable). The editor's engine mounts `lua.nx2` of the FAF data folder
(init_faf.lua), so that archive is the reference; the same files of `lua.nx5` (the newer FAF release) are read as well and a name only the older one has is reported.
The coop support mod (lobby_coop.cop, not part of the game's data) adds the functions listed in COOP below; the editor's play test defines them itself (coopshim.lua).
The Lua selftest `selftest_missiondry.lua` runs the compiled scripts against this table, the sim test (editor_mission_sim.py) against the real functions.
"""
import argparse
import hashlib
import os
import re
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import studio_paths as P  # noqa: E402

TABLE = os.path.join(P.ROOT, 'editor', 'runtime', 'lua', 'editor', 'data', 'faf_mission_api.lua')
COMPILER = [os.path.join(P.ROOT, 'editor', 'runtime', 'lua', 'editor', f) for f in ('mission.lua', 'missionplat.lua', 'mbase.lua')]

MODULES = {
    'ScenarioFramework': 'lua/ScenarioFramework.lua',
    'Objectives': 'lua/SimObjectives.lua',
    'ScenarioUtils': 'lua/sim/ScenarioUtilities.lua',
    'Cinematics': 'lua/cinematics.lua',
}
# functions of the FAF coop support mod that the coop nodes call (guarded by rawget in the script; coopshim.lua defines them for a play test): name = parameters
COOP = {'SetSharedUnitCap': 1, 'AddRestrictionForAllHumans': 1, 'RemoveRestrictionForAllHumans': 3, 'SimAnnouncement': 2, 'PlayerDeath': 3}

DEF = re.compile(r'^function\s+([A-Za-z_]\w*)\s*\(([^)]*)\)')
ASSIGN = re.compile(r'^([A-Za-z_]\w*)\s*=\s*function\s*\(([^)]*)\)')
ALIAS = re.compile(r'^([A-Za-z_]\w*)\s*=\s*(?:[A-Za-z_]\w*\.[A-Za-z_]\w*|import\(.*)\s*$')       # CreateUnitDeathTrigger = TriggerFile.CreateUnitDeathTrigger, Objectives = import(...)


def archive(name):
    path = os.path.join(P.FAF_DATA, 'gamedata', name)
    return path if os.path.isfile(path) else None


def read_member(zf, member):
    low = member.lower()
    for info in zf.infolist():
        if info.filename.lower() == low:
            return zf.read(info).decode('utf-8', errors='replace')
    return None


def params(text):
    names = [p.strip() for p in text.split(',') if p.strip()]
    if any(n.startswith('...') for n in names):
        return -1
    return len(names)


def functions(text):
    found = {}
    for line in text.splitlines():
        m = DEF.match(line) or ASSIGN.match(line)
        if m:
            found[m.group(1)] = params(m.group(2))
            continue
        m = ALIAS.match(line)
        if m and m.group(1) not in found:
            found[m.group(1)] = -1
    return found


def load(archive_name):
    """{module: {name: params}} and {module: sha1 of the file} from one archive of the game data, or None when it is not there."""
    path = archive(archive_name)
    if not path:
        return None
    result, sums = {}, {}
    with zipfile.ZipFile(path) as zf:
        for mod, member in MODULES.items():
            text = read_member(zf, member)
            if text is None:
                result[mod] = {}
                continue
            result[mod] = functions(text)
            sums[mod] = hashlib.sha1(text.encode('utf-8')).hexdigest()[:12]
    return result, sums


def render(api, sums):
    out = ['-- GENERATED by scripts/editor_mission_api.py from the game\'s own Lua (lua.nx2 of the FAF data folder): the functions a generated mission script may call.',
           '-- Do not edit; run `python scripts/editor_mission_api.py` after a FAF update. Name = number of parameters (-1 = variable).',
           '-- Used by selftest_missiondry.lua; `studio.py check` fails when the mission compiler names a function that is not here.', '',
           'Source = { archive = \'lua.nx2\', ' + ', '.join('%s = \'%s\'' % (k, v) for k, v in sorted(sums.items())) + ' }', '']
    for mod in MODULES:
        out.append('%s = {' % mod)
        for name in sorted(api[mod]):
            out.append('    %s = %d,' % (name, api[mod][name]))
        out.append('}')
        out.append('')
    out.append('-- the FAF coop support mod (not in the game data): defined by coopshim.lua for a play test')
    out.append('Coop = {')
    for name in sorted(COOP):
        out.append('    %s = %d,' % (name, COOP[name]))
    out.append('}')
    return '\n'.join(out) + '\n'


def committed():
    """The table as it is committed: {module: {name: params}} read back with the same pattern."""
    if not os.path.isfile(TABLE):
        return None
    result, current = {}, None
    for line in open(TABLE, encoding='utf-8'):
        m = re.match(r'^(\w+) = \{$', line.rstrip())
        if m:
            current = m.group(1)
            result[current] = {}
            continue
        m = re.match(r'^\s+(\w+) = (-?\d+),$', line.rstrip())
        if m and current:
            result[current][m.group(1)] = int(m.group(2))
    return result


def emitted_calls():
    """(file, module, name) for every `Module.Name` the mission compiler writes into scripts."""
    calls = set()
    pat = re.compile(r'\b(ScenarioFramework|Objectives|ScenarioUtils|Cinematics)\.([A-Za-z_]\w*)')
    obj = re.compile(r"\bObjective\('(\w+)'")       # Objective('Kill', ...) builds 'Objectives.Kill(' at run time
    for path in COMPILER:
        for line in open(path, encoding='utf-8', errors='replace'):
            for m in pat.finditer(line):
                calls.add((os.path.basename(path), m.group(1), m.group(2)))
            for m in obj.finditer(line):
                calls.add((os.path.basename(path), 'Objectives', m.group(1)))
    # the functions of the coop mod are guarded in the script (rawget) and defined by coopshim.lua for a play test: not looked up in the game's Lua; '.lua' is a file name
    return {c for c in calls if c[2] != 'lua' and not (c[1] == 'ScenarioFramework' and c[2] in COOP)}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    nx2 = load('lua.nx2')
    if not a.check:
        if not nx2:
            print('no lua.nx2 under %s: nothing written' % os.path.join(P.FAF_DATA, 'gamedata'))
            return 2
        api, sums = nx2
        open(TABLE, 'w', encoding='utf-8', newline='\n').write(render(api, sums))
        print('wrote %s (%s)' % (TABLE, ', '.join('%s %d' % (m, len(api[m])) for m in MODULES)))
        nx5 = load('lua.nx5')
        if nx5:
            for mod in MODULES:
                gone = sorted(set(api[mod]) - set(nx5[0][mod]))
                if gone:
                    print('only in lua.nx2, not in lua.nx5 (%s): %s' % (mod, ', '.join(gone[:12])))
        return 0
    bad = []
    table = committed()
    if not table:
        print('FAILED: %s is missing: run python scripts/editor_mission_api.py' % TABLE)
        return 1
    if nx2:
        api, sums = nx2
        if render(api, sums) != open(TABLE, encoding='utf-8').read():
            bad.append('the table is out of date with the game\'s Lua (lua.nx2): run python scripts/editor_mission_api.py')
    else:
        print('mission api: no lua.nx2 at %s, the committed table is not compared with the game' % P.FAF_DATA)
    for fname, mod, name in sorted(emitted_calls()):
        if name not in table.get(mod, {}):
            bad.append('%s writes %s.%s into scripts, but the game has no such function' % (fname, mod, name))
    for line in bad:
        print('FAILED: ' + line)
    if not bad:
        print('mission api: %d emitted calls exist in the game\'s Lua (%s)' % (len(emitted_calls()), ', '.join('%s %d' % (m, len(table[m])) for m in MODULES)))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
