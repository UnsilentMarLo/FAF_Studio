#!/usr/bin/env python
"""Generates the editor's help data (editor/runtime/lua/editor/helpdata.lua) from the markdown topics in editor/help/*.md.

    python scripts/gen_help.py            write helpdata.lua
    python scripts/gen_help.py --check    exit 1 when helpdata.lua is not what the topics produce (package_editor.py runs this)

Topic file format (plain on purpose, the in-game help renders only this):
    # Title                      first line
    summary: one line            optional
    keywords: a, b, c            optional, searched with the title and the text
    (blank line)
    ## Heading                   a heading
    paragraph text               a paragraph (consecutive lines are joined)
    - bullet                     a bullet
    1. step                      a numbered step
The file name (without the number prefix) is the topic id: 01_getting_started.md -> getting_started. ASCII only.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, 'editor', 'help')
OUT = os.path.join(ROOT, 'editor', 'runtime', 'lua', 'editor', 'helpdata.lua')


def q(s):
    """A Lua 5.0 string literal."""
    s = s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
    return '"' + s + '"'


def parse(path):
    text = open(path, encoding='utf-8').read()
    try:
        text.encode('ascii')
    except UnicodeEncodeError as e:
        raise SystemExit('%s: non-ASCII character at %d (%r): the in-game font set is ASCII only' % (path, e.start, text[e.start]))
    lines = text.replace('\r\n', '\n').split('\n')
    if not lines or not lines[0].startswith('# '):
        raise SystemExit('%s: the first line must be "# Title"' % path)
    topic = {'title': lines[0][2:].strip(), 'summary': '', 'keywords': '', 'blocks': []}
    para = []

    def flush():
        if para:
            topic['blocks'].append(('p', ' '.join(para)))
            para.clear()

    for line in lines[1:]:
        stripped = line.strip()
        m = re.match(r'^(summary|keywords):\s*(.*)$', stripped)
        if m and not topic['blocks'] and not para:
            topic[m.group(1)] = m.group(2)
            continue
        if not stripped:
            flush()
        elif stripped.startswith('## '):
            flush()
            topic['blocks'].append(('h', stripped[3:].strip()))
        elif stripped.startswith('- '):
            flush()
            topic['blocks'].append(('li', stripped[2:].strip()))
        elif re.match(r'^\d+\.\s', stripped):
            flush()
            n, rest = stripped.split('.', 1)
            topic['blocks'].append(('step', int(n), rest.strip()))
        else:
            para.append(stripped)
    flush()
    return topic


def generate():
    names = sorted(f for f in os.listdir(SRC) if f.endswith('.md'))
    out = ['-- GENERATED by scripts/gen_help.py from editor/help/*.md. Do not edit; edit the topics and run the script.',
           '-- Lua 5.0 dialect.', '', 'Topics = {']
    for name in names:
        topic = parse(os.path.join(SRC, name))
        tid = re.sub(r'^\d+_', '', name[:-3])
        out.append('    {')
        out.append('        id = %s, title = %s,' % (q(tid), q(topic['title'])))
        out.append('        summary = %s,' % q(topic['summary']))
        out.append('        keywords = %s,' % q(topic['keywords']))
        out.append('        blocks = {')
        for b in topic['blocks']:
            if b[0] == 'step':
                out.append('            { "step", %s, %d },' % (q(b[2]), b[1]))
            else:
                out.append('            { %s, %s },' % (q(b[0]), q(b[1])))
        out.append('        },')
        out.append('    },')
    out.append('}')
    return '\n'.join(out) + '\n'


def main():
    text = generate()
    if '--check' in sys.argv:
        have = open(OUT, encoding='utf-8', newline='').read().replace('\r\n', '\n') if os.path.exists(OUT) else ''
        if have != text:
            print('helpdata.lua is out of date: run python scripts/gen_help.py')
            sys.exit(1)
        print('helpdata.lua is up to date')
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', OUT)


if __name__ == '__main__':
    main()
