#!/usr/bin/env python
"""Where the editor's Lua swallows errors: every `pcall(...)` used as a statement (its result thrown away) and every pcall in total, per file, with the group that owns the file.

    python scripts/pcall_audit.py                 print the table
    python scripts/pcall_audit.py --write         write docs/projects/editor/BARE_PCALLS.md
    python scripts/pcall_audit.py --check N       exit 1 when the number of bare pcalls in the files of group F is above N (a ratchet for `studio.py check`)

A *bare* pcall is a statement that starts with `pcall(`: nothing looks at the result, so a failure leaves no trace. The cure is lua/editor/safe.lua (`Safe.Try(site, fn, ...)`: the same call, the
failure is logged once per site and shows in the Console). Owners are the groups of docs/projects/editor/STABILIZATION_PLAN.md; a file nobody owns is listed as `-`.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import lua_dialect as L
import studio_paths as P

OWNERS = [
    ('A', ['lua/editor/gui/widgets.lua', 'lua/editor/gui/dock.lua', 'lua/editor/gui/dialog.lua', 'lua/editor/gui/dialogs_', 'lua/editor/layoutcheck.lua']),
    ('B', ['lua/editor/overlay.lua', 'lua/editor/markervis.lua', 'lua/editor/validate.lua', 'lua/editor/units.lua', 'lua/editor/gui/panels_editor.lua', 'lua/editor/gui/shell.lua', 'lua/editor/perf.lua',
           'lua/editor/selftest_perfbudget.lua']),
    ('C', ['lua/editor/strata.lua', 'lua/editor/history.lua', 'lua/editor/maps.lua', 'lua/editor/map.lua', 'lua/editor/luaser.lua']),
    ('E', ['lua/editor/mission.lua', 'lua/editor/missionplat.lua', 'lua/editor/missionimport.lua', 'lua/editor/platoons.lua', 'lua/editor/gui/panels_mission', 'lua/editor/selftest_mission']),
    ('F', ['lua/editor/mods.lua', 'lua/editor/bpedit.lua', 'lua/editor/unitwiz.lua', 'lua/editor/unitcheck.lua', 'schook/', 'lua/editor/gui/panels_mods.lua', 'lua/editor/gui/panels_unitwiz.lua',
           'lua/editor/gui/commands.lua', 'lua/editor/gui/panels.lua', 'lua/editor/safe.lua', 'lua/editor/safeload.lua', 'lua/editor/api.lua', 'lua/editor/hookcheck.lua',
           'lua/editor/graph.lua', 'lua/editor/interop.lua', 'lua/editor/layout.lua', 'lua/editor/paths.lua', 'lua/editor/shaders.lua', 'lua/editor/terraintype.lua', 'mods/']),
]


def owner(rel):
    for group, prefixes in OWNERS:
        for p in prefixes:
            if rel == p or rel.startswith(p):
                return group
    return '-'


def scan(root):
    rows = []
    for d, dirs, fs in os.walk(root):
        dirs[:] = [x for x in dirs if x not in ('data', 'override', 'branding', 'brushes', 'maps')]
        for f in sorted(fs):
            if not f.endswith('.lua'):
                continue
            path = os.path.join(d, f)
            rel = os.path.relpath(path, root).replace(os.sep, '/')
            text = open(path, encoding='utf-8', errors='replace').read()
            toks, _ = L.lex(text)
            total = bare = intentional = 0
            lines = text.split('\n')
            for i, t in enumerate(toks):
                if t.kind == 'name' and t.val == 'pcall' and i + 1 < len(toks) and toks[i + 1].val == '(' and not (i > 0 and toks[i - 1].val in ('.', ':')):
                    total += 1
                    prev = toks[i - 1] if i > 0 else None
                    # a statement: the token before is on an earlier line, or `then` / `do` / `else` / `end` / `;` / `)` closing a header on this line
                    if prev is None or prev.line < t.line or (prev.kind == 'kw' and prev.val in ('then', 'do', 'else', 'end')) or (prev.val == ';'):
                        if 'best effort' in lines[t.line - 1]:
                            intentional += 1               # marked on the line: the failure is expected and harmless
                        else:
                            bare += 1
            if total:
                rows.append((rel, owner(rel), total, bare))
    return rows


def main():
    root = os.path.join(P.ROOT, 'editor', 'runtime')
    rows = scan(root)
    total = sum(r[2] for r in rows)
    bare = sum(r[3] for r in rows)
    by = {}
    for rel, g, t, b in rows:
        by.setdefault(g, [0, 0, 0])
        by[g][0] += 1
        by[g][1] += t
        by[g][2] += b
    lines = ['# Bare pcalls in the editor Lua', '',
             'Generated by `python scripts/pcall_audit.py --write` (do not edit by hand). A bare pcall is a statement `pcall(...)` whose result nobody reads: a failure leaves no trace.',
             'Replace it with `Safe.Try(site, fn, ...)` (`lua/editor/safe.lua`: the same call, logged once per site and shown in the Console). The owner is the group of',
             '`STABILIZATION_PLAN.md` that owns the file (`-`: nobody; whoever touches the file next converts it). Group F converted its own files; the others are listed for their groups.', '',
             '%d pcalls in %d files, %d of them bare.' % (total, len(rows), bare), '',
             '| Owner | Files | pcalls | bare |', '|---|---|---|---|']
    for g in sorted(by):
        lines.append('| %s | %d | %d | %d |' % (g, by[g][0], by[g][1], by[g][2]))
    lines += ['', '## Per file (bare first)', '', '| File | Owner | bare | pcalls |', '|---|---|---|---|']
    for rel, g, t, b in sorted(rows, key=lambda r: (-r[3], r[0])):
        if b:
            lines.append('| `%s` | %s | %d | %d |' % (rel, g, b, t))
    text = '\n'.join(lines) + '\n'
    if '--check' in sys.argv:
        limit = int(sys.argv[sys.argv.index('--check') + 1])
        mine = by.get('F', [0, 0, 0])[2]
        print('group F bare pcalls: %d (limit %d)' % (mine, limit))
        return 1 if mine > limit else 0
    if '--write' in sys.argv:
        out = os.path.join(P.ROOT, 'docs', 'projects', 'editor', 'BARE_PCALLS.md')
        open(out, 'w', encoding='utf-8', newline='\n').write(text)
        print('wrote %s' % out)
    print('\n'.join(lines[:14]))
    return 0


if __name__ == '__main__':
    sys.exit(main())
